package main

import (
	"encoding/base64"
	"fmt"
	"strings"
)

type Kitty struct {
	tmux bool
	next uint32
}

func newKitty(tmux bool) *Kitty {
	return &Kitty{tmux: tmux}
}

func (k *Kitty) nextID() uint32 {
	for {
		k.next++
		id := uint32(0x01000000) | (k.next & 0x00FFFFFF)
		if (id>>16)&0xFF == 0 || (id>>8)&0xFF == 0 || id&0xFF == 0 {
			continue
		}
		return id
	}
}

func kittyColor(id uint32) RGB {
	return RGB{uint8((id >> 16) & 0xFF), uint8((id >> 8) & 0xFF), uint8(id & 0xFF)}
}

func (k *Kitty) wrap(sequence string) string {
	if !k.tmux {
		return sequence
	}
	return "\x1bPtmux;" + strings.ReplaceAll(sequence, "\x1b", "\x1b\x1b") + "\x1b\\"
}

func (k *Kitty) Upload(thumb *Thumb) string {
	if thumb.Uploaded || len(thumb.PNG) == 0 {
		return ""
	}
	id, raw := k.UploadImage(thumb.PNG, halfWidth, imgH)
	thumb.ID = id
	thumb.Uploaded = true
	return raw
}

func (k *Kitty) UploadImage(pngData []byte, columns, rows int) (uint32, string) {
	if len(pngData) == 0 {
		return 0, ""
	}
	id := k.nextID()
	payload := base64.StdEncoding.EncodeToString(pngData)
	var builder strings.Builder
	first := true
	for len(payload) > 0 {
		chunk := payload
		more := 0
		if len(chunk) > 4096 {
			chunk = payload[:4096]
			payload = payload[4096:]
			more = 1
		} else {
			payload = ""
		}
		var sequence string
		if first {
			sequence = fmt.Sprintf("\x1b_Gf=100,t=d,i=%d,q=2,m=%d;%s\x1b\\", id, more, chunk)
			first = false
		} else {
			sequence = fmt.Sprintf("\x1b_Gm=%d;%s\x1b\\", more, chunk)
		}
		builder.WriteString(k.wrap(sequence))
	}
	builder.WriteString(k.wrap(fmt.Sprintf("\x1b_Ga=p,i=%d,c=%d,r=%d,U=1,q=2\x1b\\", id, columns, rows)))
	return id, builder.String()
}

func (k *Kitty) DeleteImage(id uint32) string {
	if id == 0 {
		return ""
	}
	return k.wrap(fmt.Sprintf("\x1b_Ga=d,i=%d,q=2\x1b\\", id))
}

